// Writes the pixel size of every artwork image into src/lib/image-sizes.generated.ts, so pages can give each <img>
// its true width and height (the browser then reserves the right space and Lighthouse's aspect-ratio check passes).
// Needs ffprobe on the PATH. Run it after `npm run assets`.
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sizes = {};
for (const dir of ["avatars", "art"]) {
  for (const file of readdirSync(path.join(root, "public", dir)).filter((f) => f.endsWith(".webp")).sort()) {
    const out = execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0", path.join(root, "public", dir, file)]).toString().trim();
    const [w, h] = out.split(",").map(Number);
    sizes[`/${dir}/${file}`] = [w, h];
  }
}

const entries = Object.entries(sizes).map(([k, v]) => `  ${JSON.stringify(k)}: [${v[0]}, ${v[1]}],`);
const NL = "\n";
writeFileSync(
  path.join(root, "src", "lib", "image-sizes.generated.ts"),
  [
    "// Generated by scripts/image-sizes.mjs - don't edit by hand.",
    "export const IMAGE_SIZES: Record<string, [number, number]> = {",
    ...entries,
    "};",
    "",
    "/** The real [width, height] of an artwork image, or a square if it isn't listed. */",
    "export const imageSize = (src: string): [number, number] => IMAGE_SIZES[src] ?? [320, 320];",
    "",
  ].join(NL),
);
console.log(`Wrote ${entries.length} sizes`);
